import {readFile,writeFile} from 'node:fs/promises';
let source='// Generated by scripts/embed-example-photo.mjs. Photo credits: assets/photos/CREDITS.md.\n';
for(const [name,file] of [['examplePhoto','team-work'],['interiorPhoto','interior'],['coffeePhoto','coffee']]){
 const bytes=await readFile(new URL(`../assets/photos/${file}.jpg`,import.meta.url));
 source+=`export const ${name}='data:image/jpeg;base64,${bytes.toString('base64')}';\n`;
}
await writeFile(new URL('../studio/src/example-photo.js',import.meta.url),source);
